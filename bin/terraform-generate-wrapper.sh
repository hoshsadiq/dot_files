#!/usr/bin/env bash

set -Euo pipefail

tmp_file_tf=""
module_tmp_file=""

cleanup() {
  [[ -n "${tmp_file_tf:-}" && -f "$tmp_file_tf" ]] && rm -f "$tmp_file_tf"
  [[ -n "${module_tmp_file:-}" && -f "$module_tmp_file" ]] && rm -f "$module_tmp_file"
}

trap cleanup EXIT

usage() {
  cat <<EOF
Usage: ${0##*/} [options]

Options:
  --root-dir <path>           Root of the terraform-aws-* repository (default: git root or cwd)
  --module-dir <path>         Module directory relative to root (e.g. modules/object)
  --wrapper-dir <path>        Directory where wrappers are written (default: wrappers)
  --module-repo-org <name>    Repository organization (default: terraform-aws-modules)
  --module-repo-shortname <s> Short name (default: derived from repo, e.g. s3-bucket)
  --overwrite                 Write generated files instead of dry-run
  --verbose                   Print debug details
  --items-key-attribute <v>   Module variable that should default to each.key
  -h, --help                  Show this help text
EOF
}

readonly GENERATED_COMMENT_TF='# WARNING: This file is automatically generated by bin/terraform-generate-wrapper.sh. Do not edit manually.'
readonly GENERATED_COMMENT_MD='<!-- WARNING: This file is automatically generated by bin/terraform-generate-wrapper.sh. Do not edit manually. -->'
readonly CONTENT_MAIN_TF='module "instances" {}'
readonly CONTENT_TAGS_VARIABLE_TF='variable "tags" {
  description = "Optional map of tags merged into every module instance."
  type        = map(string)
  default     = {}
}'
readonly CONTENT_OUTPUTS_TF='output "instances" {
  description = "Map of outputs generated by the instances module."
  value       = module.instances
}'
readonly CONTENT_VERSIONS_TF='terraform {
  required_version = ">= 1.3.0"
}'
readonly CONTENT_README='# WRAPPER_TITLE

The configuration in this directory contains an implementation of a single module wrapper pattern, which allows managing several copies of a module in places where using the native Terraform 0.13+ `for_each` feature is not feasible (e.g., with Terragrunt).

You may want to use a single Terragrunt configuration file to manage multiple resources without duplicating `terragrunt.hcl` files for each copy of the same module.

This wrapper does not implement any extra functionality.

## Usage with Terragrunt

`terragrunt.hcl`:

```hcl
terraform {
  source = "git::git@github.com:MODULE_REPO_ORG/terraform-aws-MODULE_REPO_SHORTNAME.git//WRAPPER_PATH?ref=master"
}

inputs = {
  items = {
    my-item = {
      # omitted... can be any argument supported by the module
    }
    my-second-item = {
      # omitted... can be any argument supported by the module
    }
    # omitted...
  }

  tags = {
    # optional tags applied to every item
  }
}
```

Relative path inside this repo: `WRAPPER_PATH`

## Usage with Terraform:

```hcl
module "instances" {
  source = "MODULE_REPO_ORG/MODULE_REPO_SHORTNAME/aws//WRAPPER_PATH"

  items = {
    my-item = {
      # omitted... can be any argument supported by the module
    }
    my-second-item = {
      # omitted... can be any argument supported by the module
    }
    # omitted...
  }

  tags = {
    # optional tags applied to every instance
  }
}
```

Relative path inside this repo: `WRAPPER_PATH`

## Example: Manage multiple S3 buckets in one Terragrunt layer

`eu-west-1/s3-buckets/terragrunt.hcl`:

```hcl
terraform {
  source = "git::git@github.com:terraform-aws-modules/terraform-aws-s3-bucket.git?ref=master//wrappers"
}

inputs = {
  items = {
    bucket1 = {
      bucket        = "my-random-bucket-1"
      force_destroy = true
    }
    bucket2 = {
      bucket        = "my-random-bucket-2"
      force_destroy = true
    }
  }
}
```'

build_module_hcl_cache() {
  local module_dir_path="$1"
  local -a tf_files=()

  while IFS= read -r -d '' file; do
    tf_files+=("$file")
  done < <(find "$module_dir_path" -maxdepth 1 -type f -name '*.tf' -print0)

  if [[ ${#tf_files[@]} -eq 0 ]]; then
    echo "ERROR: No Terraform (*.tf) files found in ${module_dir_path}"
    exit 1
  fi

  module_tmp_file=$(mktemp "${TMPDIR:-/tmp}/tfwrapper-module-XXXXXXXXXX")
  cat "${tf_files[@]}" > "$module_tmp_file"
}

build_structured_items_variable() {
  local module_tmp_file="$1"
  shift
  local -a module_vars=("$@")
  
  if [[ ${#module_vars[@]} -eq 0 ]]; then
    cat <<EOF
${GENERATED_COMMENT_TF}

variable "items" {
  description = "Maps of items to create a wrapper from. Values are passed through to the module."
  type        = any
  default     = {}
}
EOF
    return
  fi

  local object_attrs=()
  local description_parts=()
  description_parts+=("Maps of items to create a wrapper from. Values are passed through to the module.")
  description_parts+=("")
  description_parts+=("Each item supports the following attributes:")
  
  for module_var in "${module_vars[@]}"; do
    local var_type=""
    local var_description=""
    local var_default=""

    if ! var_type=$(hcledit attribute get "variable.${module_var}.type" -f "$module_tmp_file" 2>/dev/null); then
      var_type="any"
    else
      if [[ ${var_type:0:1} == '"' && ${var_type: -1} == '"' ]]; then
        var_type="$(jq <<<"$var_type" -r .)"
      fi
    fi
    
    if ! var_description=$(hcledit attribute get "variable.${module_var}.description" -f "$module_tmp_file" 2>/dev/null); then
      var_description=""
    else
      if [[ ${var_description:0:1} == '"' && ${var_description: -1} == '"' ]]; then
        var_description="$(jq <<<"$var_description" -r .)"
      fi
    fi

    if ! var_default=$(hcledit attribute get "variable.${module_var}.default" -f "$module_tmp_file" 2>/dev/null); then
      var_default=""
    fi

    local attr_value=""
    if [[ -z "$var_default" ]]; then
      attr_value="optional(${var_type})"
    else
      attr_value="optional(${var_type}, ${var_default})"
    fi
    
    if [[ -n "$var_description" ]]; then
      object_attrs+=("${module_var} = ${attr_value} # ${var_description}")
      description_parts+=("  - \`${module_var}\` (${var_type}): ${var_description}")
    else
      object_attrs+=("${module_var} = ${attr_value}")
      description_parts+=("  - \`${module_var}\` (${var_type})")
    fi
  done
  
  local full_description
  full_description=$(IFS=$'\n'; printf '\t%s\n' "${description_parts[@]}")
  
  cat <<EOF
${GENERATED_COMMENT_TF}

variable "items" {
  description = <<-EOT
${full_description}
	EOT
  type = map(object({
$(printf "%s\n" "${object_attrs[@]}")
  }))
  default = {}
}
EOF
}

check_dependencies() {
  if [[ ! $(command -v hcledit) ]]; then
    echo "ERROR: The binary 'hcledit' is required by this script but is not installed or in the system's PATH."
    echo "Check documentation: https://github.com/minamijoyo/hcledit"
    exit 1
  fi

  if [[ ! $(command -v terraform) ]]; then
    echo "ERROR: Terraform CLI is required to format generated files but is not installed or in the system's PATH."
    exit 1
  fi
}

create_tmp_file_tf() {
  # Can't append extension for mktemp, so renaming instead
  tmp_file=$(mktemp "${TMPDIR:-/tmp}/tfwrapper-XXXXXXXXXX")
  mv "$tmp_file" "$tmp_file.tf"
  tmp_file_tf="$tmp_file.tf"

  {
    printf "%s\n\n" "$GENERATED_COMMENT_TF"
    printf "%s\n" "$CONTENT_MAIN_TF"
  } > "$tmp_file_tf"
}

main() {
  check_dependencies

  local root_dir
  root_dir=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
  local module_dir="" # empty (default) or modules/iam-user
  local wrapper_dir="wrapper"
  local module_repo_org="terraform-aws-modules"
  local module_repo_name
  module_repo_name="$(basename "$root_dir")"
  local module_repo_shortname="${module_repo_name//terraform-aws-/}"
  local overwrite="false"
  local verbose="false"
  local items_key_attribute=""

  local newline="--newline"
  local module_has_tags="false"
  local repo_root_dir=""

  while [[ $# -gt 0 ]]; do
    local key="$1"

    case "$key" in
      --root-dir)
        root_dir="$2"
        shift
        ;;
      --module-dir)
        module_dir="$2"
        shift
        ;;
      --wrapper-dir)
        wrapper_dir="$2"
        shift
        ;;
      --module-repo-org)
        module_repo_org="$2"
        shift
        ;;
      --module-repo-shortname)
        module_repo_shortname="$2"
        shift
        ;;
      --overwrite)
        overwrite="true"
        ;;
      --verbose)
        verbose="true"
        ;;
      --items-key-attribute)
        items_key_attribute="$2"
        shift
        ;;
      -h|--help)
        usage
        exit 0
        ;;
      *)
        echo "ERROR: Unrecognized argument: $key"
        usage
        exit 1
        ;;
    esac

    shift
  done

  if [[ -z "$root_dir" ]]; then
    echo "--root-dir can't be empty. Remove it to use default value."
    exit 1
  fi

  if [[ -z "$wrapper_dir" ]]; then
    echo "--wrapper-dir can't be empty. Remove it to use default value."
    exit 1
  fi

  if [[ -z "$module_repo_org" ]]; then
    echo "--module-repo-org can't be empty. Remove it to use default value."
    exit 1
  fi

  if [[ -z "$module_repo_shortname" ]]; then
    echo "--module-repo-shortname can't be empty. It should be part of full repo name (eg, s3-bucket)."
    exit 1
  fi

  if [ ! -d "$root_dir" ]; then
    echo "Root directory $root_dir does not exist!"
    exit 1
  fi

  full_module_dir="${root_dir}/${module_dir}"

  if [ ! -d "$full_module_dir" ]; then
    echo "Module directory $full_module_dir does not exist!"
    exit 1
  fi

  if repo_root_dir=$(cd "$root_dir" && git rev-parse --show-toplevel 2>/dev/null); then
    :
  else
    repo_root_dir=""
  fi

  build_module_hcl_cache "$full_module_dir"

  # Remove "modules/" from "modules/iam-user"
  module_name="${module_dir//modules\//}"
  if [ "$module_name" == "" ]; then
    wrapper_title="Wrapper for the root module"
  else
    wrapper_title="Wrapper for module: \`${module_dir}\`"
  fi

  # Wrappers will be stored in "wrappers/{module_name}"
  output_dir="${root_dir}/${wrapper_dir}/${module_name}"

  [ ! -d "$output_dir" ] && mkdir -p "$output_dir"

  local relative_module_path
  relative_module_path=$(perl -le 'use File::Spec; print File::Spec->abs2rel(@ARGV)' "$full_module_dir" "$output_dir")

  if [[ "$relative_module_path" != ./* ]]; then
    relative_module_path="./${relative_module_path}"
  fi

  local wrapper_path=""
  if [[ -n "$repo_root_dir" ]]; then
    wrapper_path=$(perl -le 'use File::Spec; print File::Spec->abs2rel(@ARGV)' "$output_dir" "$repo_root_dir")
  else
    wrapper_path=$(perl -le 'use File::Spec; print File::Spec->abs2rel(@ARGV)' "$output_dir" "$root_dir")
  fi

  create_tmp_file_tf

  if [ "$verbose" == "true" ]; then
    echo "Root directory: $root_dir"
    echo "Module directory: $module_dir"
    echo "Output directory: $output_dir"
    echo "Temp file: $tmp_file_tf"
    echo
  fi

  # Get names of module variables in all terraform files
  local -a module_vars=()
  mapfile -t module_vars < <(hcledit block list -f "$module_tmp_file" | awk -F'.' '/^variable\./ {print $2}')

  if [ "${#module_vars[@]}" -eq 0 ]; then
    echo "WARNING: No variables detected in ${full_module_dir}; generated module will only set source/for_each."
  fi

  if [[ -n "$items_key_attribute" ]]; then
    local key_attr_found="false"
    for module_var in "${module_vars[@]}"; do
      if [[ "$module_var" == "$items_key_attribute" ]]; then
        key_attr_found="true"
        break
      fi
    done

    if [[ "$key_attr_found" == "false" ]]; then
      echo "ERROR: --items-key-attribute value '${items_key_attribute}' does not match any variable in ${module_dir}"
      exit 1
    fi
  fi

  hcledit attribute append module.instances.source "\"${relative_module_path}\"" --newline -f "$tmp_file_tf" -u
  hcledit attribute append module.instances.for_each var.items --newline -f "$tmp_file_tf" -u

  for module_var in "${module_vars[@]}"; do
    local var_default=""
    local var_type=""
    local var_value=""
    local is_tag_map="false"

    if ! var_type=$(hcledit attribute get "variable.${module_var}.type" -f "$module_tmp_file"); then
      var_type=""
    fi

    if ! var_default=$(hcledit attribute get "variable.${module_var}.default" -f "$module_tmp_file"); then
      var_default=""
    fi

    if [[ "$module_var" == "tags" && "$var_type" =~ map[[:space:]]*\([[:space:]]*string[[:space:]]*\) ]]; then
      module_has_tags="true"
      var_value="merge(var.tags, each.value.${module_var})"
    elif [[ -n "$items_key_attribute" && "$module_var" == "$items_key_attribute" ]]; then
      var_value="lookup(each.value, \"${module_var}\", each.key)"
    else
      var_value="each.value.${module_var}"
    fi

    hcledit attribute append "module.instances.${module_var}" "${var_value}" $newline -f "$tmp_file_tf" -u

    newline=""
  done

  if [ "$verbose" == "true" ]; then
    cat "$tmp_file_tf"
  fi

  if [ "$overwrite" == "true" ]; then
    echo "Saving files into ${output_dir}"

    mv "$tmp_file_tf" "${output_dir}/main.tf"
    build_structured_items_variable "$module_tmp_file" "${module_vars[@]}" > "${output_dir}/variables.tf"
    if [ "$module_has_tags" == "true" ]; then
      printf "\n%s\n" "$CONTENT_TAGS_VARIABLE_TF" >> "${output_dir}/variables.tf"
    fi
    {
      printf "%s\n\n" "$GENERATED_COMMENT_TF"
      printf "%s\n" "$CONTENT_OUTPUTS_TF"
    } > "${output_dir}/outputs.tf"
    {
      printf "%s\n\n" "$GENERATED_COMMENT_TF"
      printf "%s\n" "$CONTENT_VERSIONS_TF"
    } > "${output_dir}/versions.tf"

    local rendered_readme
    rendered_readme=$(printf "%s" "$CONTENT_README" \
      | sed \
        -e "s#WRAPPER_TITLE#${wrapper_title}#g" \
        -e "s#WRAPPER_PATH#${wrapper_path}#g" \
        -e "s#MODULE_REPO_ORG#${module_repo_org}#g" \
        -e "s#MODULE_REPO_SHORTNAME#${module_repo_shortname}#g")
    {
      printf "%s\n\n" "$GENERATED_COMMENT_MD"
      printf "%s\n" "$rendered_readme"
    } > "${output_dir}/README.md"

    if [ "$verbose" == "true" ]; then
      terraform fmt "${output_dir}"
    else
      terraform fmt "${output_dir}" >/dev/null
    fi
  else
    echo "There is nothing to save. Add --overwrite flag to write files."
  fi

}

main "$@"
